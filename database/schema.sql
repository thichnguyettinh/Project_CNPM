-- Lop Minh relational schema for PostgreSQL 14+.
-- Apply with: psql "$DATABASE_URL" -v ON_ERROR_STOP=1 -f database/schema.sql

CREATE TABLE IF NOT EXISTS users (
  user_id        VARCHAR(36) PRIMARY KEY,
  username       VARCHAR(50) NOT NULL UNIQUE,
  email          VARCHAR(254) UNIQUE,
  password_hash  VARCHAR(255) NOT NULL,
  role           VARCHAR(20) NOT NULL CHECK (role IN ('teacher', 'student', 'parent')),
  full_name      VARCHAR(150) NOT NULL,
  phone          VARCHAR(30),
  avatar_text    VARCHAR(10),
  status         VARCHAR(20) NOT NULL DEFAULT 'active'
                 CHECK (status IN ('active', 'inactive', 'locked')),
  failed_login_attempts SMALLINT NOT NULL DEFAULT 0
                 CHECK (failed_login_attempts BETWEEN 0 AND 3),
  locked_until   TIMESTAMPTZ,
  created_at     TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_at     TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
ALTER TABLE users ADD COLUMN IF NOT EXISTS failed_login_attempts SMALLINT NOT NULL DEFAULT 0;
ALTER TABLE users ADD COLUMN IF NOT EXISTS locked_until TIMESTAMPTZ;
CREATE INDEX IF NOT EXISTS idx_users_role_status ON users (role, status);

CREATE TABLE IF NOT EXISTS user_aliases (
  alias_id  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id   VARCHAR(36) NOT NULL REFERENCES users(user_id) ON DELETE CASCADE,
  alias     VARCHAR(254) NOT NULL UNIQUE
);
CREATE INDEX IF NOT EXISTS idx_user_aliases_user ON user_aliases (user_id);

CREATE TABLE IF NOT EXISTS user_profiles (
  user_id       VARCHAR(36) PRIMARY KEY REFERENCES users(user_id) ON DELETE CASCADE,
  date_of_birth DATE,
  address       VARCHAR(255),
  biography     TEXT
);

CREATE TABLE IF NOT EXISTS user_avatars (
  user_id       VARCHAR(36) PRIMARY KEY REFERENCES users(user_id) ON DELETE CASCADE,
  mime_type     VARCHAR(30) NOT NULL CHECK (mime_type IN ('image/jpeg', 'image/png', 'image/webp')),
  image_data    BYTEA NOT NULL,
  updated_at    TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS auth_sessions (
  session_id    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id       VARCHAR(36) NOT NULL REFERENCES users(user_id) ON DELETE CASCADE,
  token_hash    CHAR(64) NOT NULL UNIQUE,
  created_at    TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  expires_at    TIMESTAMPTZ NOT NULL,
  revoked_at    TIMESTAMPTZ
);
CREATE INDEX IF NOT EXISTS idx_auth_sessions_user_expiry ON auth_sessions (user_id, expires_at);

CREATE TABLE IF NOT EXISTS students (
  student_id    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  student_code  VARCHAR(30) NOT NULL UNIQUE,
  user_id       VARCHAR(36) UNIQUE REFERENCES users(user_id) ON DELETE SET NULL,
  status        VARCHAR(20) NOT NULL DEFAULT 'active'
                CHECK (status IN ('active', 'inactive', 'graduated')),
  created_at    TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS parents (
  parent_id  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id    VARCHAR(36) UNIQUE REFERENCES users(user_id) ON DELETE SET NULL,
  full_name  VARCHAR(150) NOT NULL,
  phone      VARCHAR(30),
  email      VARCHAR(254)
);
CREATE INDEX IF NOT EXISTS idx_parents_name ON parents (full_name);

CREATE TABLE IF NOT EXISTS student_parents (
  student_id    BIGINT NOT NULL REFERENCES students(student_id) ON DELETE CASCADE,
  parent_id     BIGINT NOT NULL REFERENCES parents(parent_id) ON DELETE CASCADE,
  relationship  VARCHAR(40),
  is_primary    BOOLEAN NOT NULL DEFAULT FALSE,
  linked_at     TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  PRIMARY KEY (student_id, parent_id)
);
CREATE INDEX IF NOT EXISTS idx_student_parents_parent ON student_parents (parent_id);

CREATE TABLE IF NOT EXISTS classes (
  class_id         VARCHAR(36) PRIMARY KEY,
  class_code       VARCHAR(30) NOT NULL UNIQUE,
  name             VARCHAR(150) NOT NULL,
  subject          VARCHAR(100) NOT NULL,
  teacher_user_id  VARCHAR(36) NOT NULL REFERENCES users(user_id) ON DELETE RESTRICT,
  monthly_fee      NUMERIC(12,2) NOT NULL DEFAULT 0 CHECK (monthly_fee >= 0),
  default_room     VARCHAR(100),
  description      TEXT,
  status           VARCHAR(20) NOT NULL DEFAULT 'planned'
                   CHECK (status IN ('planned', 'active', 'completed', 'archived')),
  created_at       TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_at       TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
CREATE INDEX IF NOT EXISTS idx_classes_teacher_status ON classes (teacher_user_id, status);

CREATE TABLE IF NOT EXISTS class_enrollments (
  enrollment_id  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  class_id       VARCHAR(36) NOT NULL REFERENCES classes(class_id) ON DELETE RESTRICT,
  student_id     BIGINT NOT NULL REFERENCES students(student_id) ON DELETE RESTRICT,
  enrolled_on    DATE NOT NULL,
  ended_on       DATE,
  status         VARCHAR(20) NOT NULL DEFAULT 'active'
                 CHECK (status IN ('active', 'ended', 'withdrawn')),
  CHECK (ended_on IS NULL OR ended_on >= enrolled_on),
  UNIQUE (class_id, student_id, enrolled_on)
);
CREATE INDEX IF NOT EXISTS idx_enrollments_student_status ON class_enrollments (student_id, status);
CREATE INDEX IF NOT EXISTS idx_enrollments_class_status ON class_enrollments (class_id, status);

CREATE TABLE IF NOT EXISTS class_schedule_rules (
  schedule_rule_id  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  class_id          VARCHAR(36) NOT NULL REFERENCES classes(class_id) ON DELETE CASCADE,
  weekday           SMALLINT NOT NULL CHECK (weekday BETWEEN 1 AND 7),
  starts_at         TIME NOT NULL,
  ends_at           TIME NOT NULL CHECK (ends_at > starts_at),
  room              VARCHAR(100),
  effective_from    DATE NOT NULL,
  effective_until   DATE CHECK (effective_until IS NULL OR effective_until >= effective_from)
);
CREATE INDEX IF NOT EXISTS idx_schedule_rules_class_day ON class_schedule_rules (class_id, weekday, effective_from);

CREATE TABLE IF NOT EXISTS class_sessions (
  session_id  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  class_id    VARCHAR(36) NOT NULL REFERENCES classes(class_id) ON DELETE RESTRICT,
  starts_at   TIMESTAMPTZ NOT NULL,
  ends_at     TIMESTAMPTZ NOT NULL CHECK (ends_at > starts_at),
  room        VARCHAR(100),
  topic       VARCHAR(255),
  status      VARCHAR(20) NOT NULL DEFAULT 'scheduled'
              CHECK (status IN ('scheduled', 'completed', 'cancelled')),
  created_by  VARCHAR(36) NOT NULL REFERENCES users(user_id) ON DELETE RESTRICT,
  created_at  TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_at  TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
CREATE INDEX IF NOT EXISTS idx_sessions_class_start ON class_sessions (class_id, starts_at);
CREATE INDEX IF NOT EXISTS idx_sessions_start_status ON class_sessions (starts_at, status);

CREATE TABLE IF NOT EXISTS attendance_records (
  session_id  BIGINT NOT NULL REFERENCES class_sessions(session_id) ON DELETE CASCADE,
  student_id  BIGINT NOT NULL REFERENCES students(student_id) ON DELETE RESTRICT,
  status      VARCHAR(20) NOT NULL DEFAULT 'present'
              CHECK (status IN ('present', 'absent', 'late', 'excused')),
  note        VARCHAR(500),
  marked_by   VARCHAR(36) REFERENCES users(user_id) ON DELETE SET NULL,
  marked_at   TIMESTAMPTZ,
  PRIMARY KEY (session_id, student_id)
);
CREATE INDEX IF NOT EXISTS idx_attendance_student_status ON attendance_records (student_id, status);

CREATE TABLE IF NOT EXISTS assignments (
  assignment_id    VARCHAR(36) PRIMARY KEY,
  class_id         VARCHAR(36) NOT NULL REFERENCES classes(class_id) ON DELETE RESTRICT,
  title            VARCHAR(200) NOT NULL,
  assignment_type  VARCHAR(50) NOT NULL,
  description      TEXT,
  assigned_at      DATE NOT NULL,
  due_at           TIMESTAMPTZ,
  status           VARCHAR(20) NOT NULL DEFAULT 'published'
                   CHECK (status IN ('draft', 'published', 'closed')),
  created_by       VARCHAR(36) NOT NULL REFERENCES users(user_id) ON DELETE RESTRICT,
  created_at       TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_at       TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
CREATE INDEX IF NOT EXISTS idx_assignments_class_date ON assignments (class_id, assigned_at);
CREATE INDEX IF NOT EXISTS idx_assignments_due_status ON assignments (due_at, status);

