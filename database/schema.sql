CREATE TABLE IF NOT EXISTS assignment_attachments (
  assignment_id VARCHAR(36) PRIMARY KEY REFERENCES assignments(assignment_id) ON DELETE CASCADE,
  file_name VARCHAR(255) NOT NULL,
  storage_key VARCHAR(100) NOT NULL UNIQUE,
  mime_type VARCHAR(100) NOT NULL,
  file_size BIGINT NOT NULL CHECK (file_size > 0),
  uploaded_by VARCHAR(36) NOT NULL REFERENCES users(user_id) ON DELETE RESTRICT,
  uploaded_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS assignment_submissions (
  submission_id  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  assignment_id  VARCHAR(36) NOT NULL REFERENCES assignments(assignment_id) ON DELETE CASCADE,
  student_id     BIGINT NOT NULL REFERENCES students(student_id) ON DELETE RESTRICT,
  file_name      VARCHAR(255) NOT NULL,
  storage_key    VARCHAR(500) NOT NULL,
  mime_type      VARCHAR(100),
  file_size      BIGINT CHECK (file_size IS NULL OR file_size >= 0),
  submitted_at   TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  status         VARCHAR(20) NOT NULL DEFAULT 'submitted'
                 CHECK (status IN ('submitted', 'late', 'returned'))
);
CREATE INDEX IF NOT EXISTS idx_submissions_assignment_student ON assignment_submissions (assignment_id, student_id, submitted_at);

CREATE TABLE IF NOT EXISTS assignment_results (
  assignment_id    VARCHAR(36) NOT NULL REFERENCES assignments(assignment_id) ON DELETE CASCADE,
  student_id       BIGINT NOT NULL REFERENCES students(student_id) ON DELETE RESTRICT,
  score            NUMERIC(4,2) CHECK (
                     score IS NULL OR
                     (score BETWEEN 0 AND 10 AND score * 2 = FLOOR(score * 2))
                   ),
  teacher_comment  TEXT,
  graded_by        VARCHAR(36) REFERENCES users(user_id) ON DELETE SET NULL,
  graded_at        TIMESTAMPTZ,
  PRIMARY KEY (assignment_id, student_id)
);
CREATE INDEX IF NOT EXISTS idx_results_student ON assignment_results (student_id, graded_at);

CREATE TABLE IF NOT EXISTS grade_change_logs (
  grade_change_id  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  assignment_id    VARCHAR(36) NOT NULL,
  student_id       BIGINT NOT NULL,
  old_score        NUMERIC(4,2) CHECK (
                     old_score IS NULL OR
                     (old_score BETWEEN 0 AND 10 AND old_score * 2 = FLOOR(old_score * 2))
                   ),
  new_score        NUMERIC(4,2) CHECK (
                     new_score IS NULL OR
                     (new_score BETWEEN 0 AND 10 AND new_score * 2 = FLOOR(new_score * 2))
                   ),
  reason           VARCHAR(500) NOT NULL,
  changed_by       VARCHAR(36) NOT NULL REFERENCES users(user_id) ON DELETE RESTRICT,
  changed_at       TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  FOREIGN KEY (assignment_id, student_id)
    REFERENCES assignment_results(assignment_id, student_id) ON DELETE RESTRICT
);
CREATE INDEX IF NOT EXISTS idx_grade_changes_result ON grade_change_logs (assignment_id, student_id, changed_at);

