CREATE TABLE IF NOT EXISTS assignment_question_scores (
  assignment_id VARCHAR(36) NOT NULL,
  student_id BIGINT NOT NULL,
  question_no SMALLINT NOT NULL CHECK (question_no BETWEEN 1 AND 100),
  max_score NUMERIC(4,2) NOT NULL CHECK (max_score > 0 AND max_score <= 10 AND max_score * 2 = FLOOR(max_score * 2)),
  earned_score NUMERIC(4,2) NOT NULL CHECK (earned_score >= 0 AND earned_score <= max_score AND earned_score * 2 = FLOOR(earned_score * 2)),
  PRIMARY KEY (assignment_id, student_id, question_no),
  FOREIGN KEY (assignment_id, student_id)
    REFERENCES assignment_results(assignment_id, student_id) ON DELETE CASCADE
);

CREATE TABLE IF NOT EXISTS tuition_invoices (
  invoice_id      VARCHAR(36) PRIMARY KEY,
  student_id      BIGINT NOT NULL REFERENCES students(student_id) ON DELETE RESTRICT,
  class_id        VARCHAR(36) NOT NULL REFERENCES classes(class_id) ON DELETE RESTRICT,
  billing_year    SMALLINT NOT NULL,
  billing_month   SMALLINT NOT NULL CHECK (billing_month BETWEEN 1 AND 12),
  period_start    DATE NOT NULL,
  period_end      DATE NOT NULL CHECK (period_end >= period_start),
  sessions_count  SMALLINT NOT NULL DEFAULT 0 CHECK (sessions_count >= 0),
  amount_due      NUMERIC(12,2) NOT NULL CHECK (amount_due >= 0),
  note            VARCHAR(500),
  issued_by       VARCHAR(36) NOT NULL REFERENCES users(user_id) ON DELETE RESTRICT,
  issued_at       TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  status          VARCHAR(20) NOT NULL DEFAULT 'open' CHECK (status IN ('open', 'void')),
  UNIQUE (student_id, class_id, billing_year, billing_month)
);
CREATE INDEX IF NOT EXISTS idx_invoices_class_period ON tuition_invoices (class_id, billing_year, billing_month);
CREATE INDEX IF NOT EXISTS idx_invoices_student_status ON tuition_invoices (student_id, status);

CREATE TABLE IF NOT EXISTS tuition_payments (
  payment_id      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  invoice_id      VARCHAR(36) NOT NULL REFERENCES tuition_invoices(invoice_id) ON DELETE RESTRICT,
  amount          NUMERIC(12,2) NOT NULL CHECK (amount > 0),
  payment_method  VARCHAR(30) NOT NULL CHECK (payment_method IN ('cash', 'bank_transfer', 'other')),
  paid_at         TIMESTAMPTZ NOT NULL,
  reference_code  VARCHAR(100),
  note            VARCHAR(500),
  recorded_by     VARCHAR(36) NOT NULL REFERENCES users(user_id) ON DELETE RESTRICT,
  created_at      TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
CREATE INDEX IF NOT EXISTS idx_payments_invoice_date ON tuition_payments (invoice_id, paid_at);

CREATE TABLE IF NOT EXISTS notifications (
  notification_id   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  recipient_user_id VARCHAR(36) NOT NULL REFERENCES users(user_id) ON DELETE CASCADE,
  title             VARCHAR(200) NOT NULL,
  body              TEXT NOT NULL,
  category          VARCHAR(20) NOT NULL DEFAULT 'system'
                    CHECK (category IN ('academic', 'assignment', 'tuition', 'system')),
  invoice_id        VARCHAR(36) REFERENCES tuition_invoices(invoice_id) ON DELETE SET NULL,
  created_at        TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  read_at           TIMESTAMPTZ
);
CREATE INDEX IF NOT EXISTS idx_notifications_recipient_created ON notifications (recipient_user_id, created_at DESC);

CREATE OR REPLACE VIEW v_tuition_invoice_balances AS
SELECT
  i.invoice_id,
  i.student_id,
  i.class_id,
  i.billing_year,
  i.billing_month,
  i.amount_due,
  COALESCE(SUM(p.amount), 0)::NUMERIC(12,2) AS amount_paid,
  GREATEST(i.amount_due - COALESCE(SUM(p.amount), 0), 0)::NUMERIC(12,2) AS amount_remaining,
  CASE
    WHEN i.status = 'void' THEN 'void'
    WHEN COALESCE(SUM(p.amount), 0) = 0 THEN 'unpaid'
    WHEN COALESCE(SUM(p.amount), 0) < i.amount_due THEN 'partial'
    ELSE 'paid'
  END AS payment_status
FROM tuition_invoices AS i
LEFT JOIN tuition_payments AS p ON p.invoice_id = i.invoice_id
GROUP BY i.invoice_id;
