CREATE TABLE IF NOT EXISTS absence_requests (
  request_id   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  session_id   BIGINT NOT NULL REFERENCES class_sessions(session_id) ON DELETE CASCADE,
  student_id   BIGINT NOT NULL REFERENCES students(student_id) ON DELETE RESTRICT,
  requested_by VARCHAR(36) NOT NULL REFERENCES users(user_id) ON DELETE RESTRICT,
  reason       VARCHAR(500) NOT NULL CHECK (length(btrim(reason)) > 0),
  status       VARCHAR(20) NOT NULL DEFAULT 'pending' CHECK (status IN ('pending', 'acknowledged')),
  created_at   TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  UNIQUE (session_id, student_id)
);
CREATE INDEX IF NOT EXISTS idx_absence_requests_session_created
  ON absence_requests (session_id, created_at DESC);
CREATE INDEX IF NOT EXISTS idx_absence_requests_student_created
  ON absence_requests (student_id, created_at DESC);
